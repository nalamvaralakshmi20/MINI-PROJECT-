package Dbconn;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

public class CreateFeedbackTable {
    public static void main(String[] args) {
        try {
            Class.forName("oracle.jdbc.OracleDriver");
            Connection con = DriverManager.getConnection(
                    "jdbc:oracle:thin:@localhost:1521/FREEPDB1",
                    "shoaib",
                    "system"
            );

            Statement st = con.createStatement();

            // Create the feedback table
            String sql = "CREATE TABLE feedback (" +
                         "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                         "student_name VARCHAR2(100) NOT NULL, " +
                         "roll_no VARCHAR2(20) NOT NULL, " +
                         "course VARCHAR2(50), " +
                         "feedback_text VARCHAR2(500), " +
                         "submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP)";
            st.executeUpdate(sql);

            System.out.println("Feedback table created successfully!");

            con.close();
        } catch (Exception e) {
            System.out.println("Error: " + e.getMessage());
            e.printStackTrace();
        }
    }
}
